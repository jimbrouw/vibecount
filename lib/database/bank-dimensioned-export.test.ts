import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile, readdir } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto';
import { TEST_SCHEMA_BOOTSTRAP } from './test-schema';
import { bankValuationFixture, openSyntheticForeignAdmission } from './bank-valuation-fixture';
import { bankExportContext, type BankExportRow, type BankExportFamily } from '../records/bank-export-context';
import { bankEvidenceLedger, bankEvidenceManifest } from '../records/bank-dimensioned-export';
import { rateFromDecimal } from '../fx/currency';
import { FX_PROVENANCE_SCHEMA, FX_PROVENANCE_SCOPE } from '../fx/provenance';
import { canonicalJson, sha256 } from '../tax/snapshot';
import { readSourceCsv } from '../records/source-csv';

test('bank exports retain complete actual SQL valuation ancestry, exact originals and zero/stale/withdrawn states', async t => {
  const db = new PGlite({ extensions: { pgcrypto } });
  t.after(() => db.close());
  await db.exec(TEST_SCHEMA_BOOTSTRAP);
  const dir = new URL('../../supabase/migrations/', import.meta.url);
  for (const name of (await readdir(dir)).filter(n => n.endsWith('.sql')).sort()) await db.exec(await readFile(new URL(name, dir), 'utf8'));
  await db.exec('begin');
  try {
    await openSyntheticForeignAdmission(db);
    const f = await bankValuationFixture(db);
    const read = async () => {
      await db.query("select set_config('request.jwt.claim.sub',$1,false)", [f.owner]);
      const coverage = (await db.query<{ c: unknown }>('select read_bank_source_coverage() c')).rows[0].c;
      const rows = (await db.query<{ r: BankExportRow }>(`select to_jsonb(t)||jsonb_build_object('source_rows',jsonb_build_object('row_number',s.row_number,'row_hash',s.row_hash),'record_imports',jsonb_build_object('id',i.id,'user_id',i.user_id,'source_file_id',i.source_file_id,'file_hash',i.file_hash,'parser_version',i.parser_version),'record','[]'::jsonb,'refund_portions','[]'::jsonb) r from bank_transactions t join source_rows s on s.id=t.source_row_id join record_imports i on i.id=t.import_id where t.user_id=$1 order by t.id`, [f.owner])).rows.map(r => r.r);
      const families = (await db.query<BankExportFamily>('select id,user_id,transaction_id from bank_valuation_families where user_id=$1', [f.owner])).rows;
      const revisions = (await db.query<{ r: Record<string,unknown> }>("select to_jsonb(v)-'fingerprint' r from bank_valuation_revisions v where user_id=$1 order by ordinal", [f.owner])).rows.map(r => r.r);
      return { coverage, rows, families, revisions, context: bankExportContext(f.owner, coverage, rows, families, revisions, f.imported) };
    };
    const empty = await read();
    assert.equal(empty.context.snapshot.observations[0].original_signed_minor, '-10001');
    assert.equal(empty.context.snapshot.observations[0].signed_amount_pence, null);
    assert.equal(empty.context.snapshot.observations[0].currency_exponent, 3);
    assert.equal(empty.context.snapshot.observations[0].valuation_status, 'unvalued');
    await f.record(await f.intent({ state: 'provisional', human_read_original: false }));
    await f.record(await f.intent({ expected_ordinal: 1, data: { method: 'documented_rate/1', rate: rateFromDecimal('KWD','GBP','0.00001'), valuation_date: '2026-04-06', evidence_date: '2026-04-07' } }));
    const reviewed = await read(), observation = reviewed.context.snapshot.observations[0];
    assert.equal(observation.valuation_status, 'reviewed_zero');
    assert.equal(observation.valuation_history.length, 2);
    assert.equal(observation.valuation_history[1].signed_gbp_pence, 0);
    assert.equal(observation.recognized_expense_pence, 0);
    assert.equal(observation.signed_amount_pence, null);
    const [header, row] = readSourceCsv(bankEvidenceLedger(reviewed.context).csv);
    assert.equal(row[header.indexOf('original_signed_minor')], '-10001');
    assert.equal(row[header.indexOf('actual_signed_gbp_pence')], '');
    const manifest = bankEvidenceManifest(f.owner, reviewed.context, { schema_version: FX_PROVENANCE_SCHEMA, scope: FX_PROVENANCE_SCOPE, owner_id: f.owner, counts: { lots: 0, events: 0 }, lots: [], events: [] });
    assert.equal(manifest.snapshot_sha256, sha256(canonicalJson(manifest.snapshot)));
    assert.doesNotMatch(JSON.stringify(manifest), /object_path|key_id|raw_encrypted|Synthetic foreign observation/);
    const build = (rows = reviewed.rows, families = reviewed.families, revisions = reviewed.revisions) => bankExportContext(f.owner, reviewed.coverage, rows, families, revisions, f.imported);
    assert.throws(() => build([]));
    assert.throws(() => build(reviewed.rows, []));
    assert.throws(() => build(reviewed.rows, reviewed.families, reviewed.revisions.slice(1)));
    assert.throws(() => build(reviewed.rows, reviewed.families, reviewed.revisions.slice(0,1)));
    assert.throws(() => build([{ ...reviewed.rows[0], user_id: f.other }]));
    assert.throws(() => build([{ ...reviewed.rows[0], original_signed_minor: '-10000' }]));
    assert.throws(() => build(reviewed.rows, reviewed.families, [reviewed.revisions[0], { ...reviewed.revisions[1], previous_revision_id: f.other }]));
    assert.throws(() => build(reviewed.rows, reviewed.families, [reviewed.revisions[0], { ...reviewed.revisions[1], request_id: reviewed.revisions[0].request_id }]));
    await db.query('delete from storage.objects where name=$1', [f.documentPath]);
    assert.equal((await read()).context.snapshot.observations[0].valuation_status, 'stale');
    await f.record(await f.intent({ expected_ordinal: 2, state: 'withdrawn', document_id: null, transaction_version: null, data: null, human_read_original: false }));
    await db.query("update record_imports set status='discarded' where id=$1", [f.imported]);
    const withdrawn = (await read()).context.snapshot;
    assert.equal(withdrawn.observation_count, 1);
    assert.equal(withdrawn.observations[0].import_status, 'discarded');
    assert.equal(withdrawn.observations[0].valuation_status, 'withdrawn');
    assert.equal(withdrawn.observations[0].valuation_history.length, 3);
    assert.equal((await db.query('select id from financial_records where user_id=$1', [f.owner])).rows.length, 0);
  } finally { await db.exec('rollback'); }
  assert.equal((await db.query('select id from bank_transactions')).rows.length, 0);
});
